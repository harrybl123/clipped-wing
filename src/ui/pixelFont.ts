const MISSING: readonly string[] = ['###', '#.#', '#.#', '#.#', '#.#', '#.#', '###'];

/** Swaps typographic characters for ones the font has. */
export function normaliseText(text: string): string {
  return text
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/…/g, '...');
}

export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS;
}

export function glyphFor(ch: string): readonly string[] {
  return GLYPHS[ch] ?? MISSING;
}

/** Characters the font defines (for tests). */
export function definedCharacters(): string[] {
  return Object.keys(GLYPHS);
}

/** Width of one line in font pixels (1px gap between glyphs). */
export function measure(text: string): number {
  const chars = [...normaliseText(text)];
  if (chars.length === 0) return 0;
  return chars.reduce((w, ch) => w + glyphFor(ch)[0]!.length + 1, -1);
}

/** Splits text into lines no wider than maxWidth font pixels, breaking at spaces and \n. */
export function wrap(text: string, maxWidth = Infinity): string[] {
  const lines: string[] = [];
  for (const paragraph of normaliseText(text).split('\n')) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      const candidate = line === '' ? word : `${line} ${word}`;
      if (line !== '' && measure(candidate) > maxWidth) {
        lines.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    lines.push(line);
  }
  return lines;
}

/** Size of wrapped text in font pixels. */
export function layout(text: string, maxWidth = Infinity): { lines: string[]; width: number; height: number } {
  const lines = wrap(text, maxWidth);
  return {
    lines,
    width: Math.max(0, ...lines.map(measure)),
    height: (lines.length - 1) * LINE_HEIGHT + GLYPH_ROWS,
  };
}

/** Draws one line of text with fillRect calls (canvas-like), top-left at (x, y). */
export function drawLine(target: { fillRect(x: number, y: number, w: number, h: number): void }, text: string, x: number, y: number, scale = 1): void {
  let cursor = x;
  for (const ch of normaliseText(text)) {
    const glyph = glyphFor(ch);
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] === '#') target.fillRect(cursor + gx * scale, y + gy * scale, scale, scale);
      }
    });
    cursor += (glyph[0]!.length + 1) * scale;
  }
}
